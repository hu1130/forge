DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'forge_app') THEN
    CREATE ROLE forge_app LOGIN PASSWORD 'forge_app_dev_only';
  END IF;
END
$$;

ALTER ROLE forge_app
  NOSUPERUSER
  NOCREATEDB
  NOCREATEROLE
  NOINHERIT
  NOBYPASSRLS;

GRANT CONNECT ON DATABASE forge TO forge_app;
GRANT USAGE ON SCHEMA public TO forge_app;
REVOKE CREATE ON SCHEMA public FROM forge_app;
GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES ON ALL TABLES IN SCHEMA public TO forge_app;
ALTER DEFAULT PRIVILEGES FOR ROLE forge IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES ON TABLES TO forge_app;
